CREATE OR REPLACE FUNCTION public.verifier_connexion(p_id text, p_mdp text)
 RETURNS TABLE(id text, prenom text, nom text, role text, dept text, email text, tel text, droits jsonb, doit_changer_mdp boolean, statut text, saisonnier boolean)
 LANGUAGE plpgsql SECURITY DEFINER SET search_path TO 'public', 'extensions'
AS $function$
declare v_ok boolean := false; v_statut text;
begin
  select (s.mdp_hash is not null and s.mdp_hash = crypt(p_mdp, s.mdp_hash)), c.statut into v_ok, v_statut
    from public.comptes c left join public.comptes_secrets s on s.id = c.id where c.id = p_id;
  if v_ok is null or v_ok = false then
    insert into public.audit_log(acteur, action, ressource, ressource_id, details)
    values (p_id, 'ECHEC_CONNEXION', 'comptes', p_id, jsonb_build_object('motif','identifiants invalides'));
    return;
  end if;
  if coalesce(v_statut,'actif') = 'inactif' then
    insert into public.audit_log(acteur, action, ressource, ressource_id, details)
    values (p_id, 'ECHEC_CONNEXION', 'comptes', p_id, jsonb_build_object('motif','compte désactivé'));
    return;
  end if;
  insert into public.audit_log(acteur, action, ressource, ressource_id) values (p_id, 'CONNEXION', 'comptes', p_id);
  return query
    select c.id, c.prenom, c.nom, c.role, c.dept, c.email, c.tel, to_jsonb(c.droits), coalesce(s.doit_changer_mdp, false),
           coalesce(c.statut,'actif'), coalesce(c.saisonnier,false)
      from public.comptes c left join public.comptes_secrets s on s.id = c.id where c.id = p_id;
end $function$;

