CREATE OR REPLACE FUNCTION public._ft_remplacer_site(p_days jsonb, p_src text, p_dst text)
 RETURNS jsonb LANGUAGE sql IMMUTABLE
AS $function$
  select coalesce(jsonb_agg(
    case when jsonb_typeof(d->'tasks') = 'array' then jsonb_set(d, '{tasks}', coalesce((
      select jsonb_agg(case when t->>'siteId' = p_src then t || jsonb_build_object('siteId', p_dst) else t end order by o)
      from jsonb_array_elements(d->'tasks') with ordinality x(t, o)), '[]'::jsonb))
    else d end order by i), '[]'::jsonb)
  from jsonb_array_elements(p_days) with ordinality y(d, i)
$function$;

CREATE OR REPLACE FUNCTION public.admin_definir_mdp(p_admin_id text, p_admin_mdp text, p_cible_id text, p_nouveau text)
 RETURNS boolean LANGUAGE plpgsql SECURITY DEFINER SET search_path TO 'public', 'extensions'
AS $function$
declare v_ok boolean := false; v_role text;
begin
  select (s.mdp_hash is not null and s.mdp_hash = crypt(p_admin_mdp, s.mdp_hash)), c.role into v_ok, v_role
    from public.comptes c left join public.comptes_secrets s on s.id = c.id where c.id = p_admin_id;
  if v_ok is null or v_ok = false or v_role is distinct from 'admin' then
    insert into public.audit_log(acteur, action, ressource, ressource_id, details)
    values (p_admin_id, 'ECHEC_CONNEXION', 'comptes.mdp', p_cible_id, jsonb_build_object('motif','définition de mot de passe refusée'));
    return false;
  end if;
  if length(coalesce(p_nouveau,'')) < 8 then raise exception 'Le mot de passe doit contenir au moins 8 caractères'; end if;
  if not exists (select 1 from public.comptes c where c.id = p_cible_id) then raise exception 'Compte introuvable'; end if;
  insert into public.comptes_secrets (id, mdp_hash, mdp_maj_le, doit_changer_mdp)
  values (p_cible_id, crypt(p_nouveau, gen_salt('bf', 10)), now(), p_cible_id <> p_admin_id)
  on conflict (id) do update set mdp_hash = excluded.mdp_hash, mdp_maj_le = excluded.mdp_maj_le, doit_changer_mdp = excluded.doit_changer_mdp;
  insert into public.audit_log(acteur, action, ressource, ressource_id, details)
  values (p_admin_id, 'MODIFICATION', 'comptes.mdp', p_cible_id, jsonb_build_object('motif','mot de passe défini par un administrateur (sa-admin)'));
  return true;
end $function$;

CREATE OR REPLACE FUNCTION public.changer_mdp(p_id text, p_ancien text, p_nouveau text)
 RETURNS boolean LANGUAGE plpgsql SECURITY DEFINER SET search_path TO 'public', 'extensions'
AS $function$
declare v_ok boolean := false;
begin
  if length(coalesce(p_nouveau,'')) < 8 then
    raise exception 'Le mot de passe doit contenir au moins 8 caractères';
  end if;
  select (s.mdp_hash is not null and s.mdp_hash = crypt(p_ancien, s.mdp_hash))
    into v_ok from public.comptes_secrets s where s.id = p_id;
  if v_ok is null or v_ok = false then
    insert into public.audit_log(acteur, action, ressource, ressource_id, details)
    values (p_id, 'ECHEC_CONNEXION', 'comptes', p_id, jsonb_build_object('motif','ancien mot de passe invalide'));
    return false;
  end if;
  update public.comptes_secrets
     set mdp_hash = crypt(p_nouveau, gen_salt('bf', 10)), mdp_maj_le = now(), doit_changer_mdp = false
   where id = p_id;
  insert into public.audit_log(acteur, action, ressource, ressource_id)
  values (p_id, 'MODIFICATION', 'comptes.mdp', p_id);
  return true;
end $function$;

